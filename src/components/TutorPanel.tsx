const GREETING =
  "I'm Socratic, your lab tutor. I can see your canvas, your examples and your last mistake — but I'll never hand you the fix. Ask me anything, or say **\"hint\"**.";

/** Strip the model's private reasoning block from any text that leaves the panel. */
export function stripThink(text: string): string {
  return text.replace(/<think>[\s\S]*?<\/think>/gi, "").trim();
}

function splitThink(text: string): { think: string | null; body: string } {
  const m = text.match(/<think>([\s\S]*?)<\/think>/i);
  return { think: m?.[1]?.trim() || null, body: stripThink(text) };
}

function speak(text: string) {
  if (typeof window === "undefined" || !("speechSynthesis" in window)) return;
  const utter = new SpeechSynthesisUtterance(text);
  utter.rate = 1;
  window.speechSynthesis.cancel();
  window.speechSynthesis.speak(utter);
}

/**
 * Cross-session recall, grounded in persisted app performance data (never in
 * chat content). Aggregate stats the student generated by using the app.
 */
function recallOpener(): string | null {
  const top = Storage.getMistakeSummary().data[0];
  const solved = Storage.countSolvedUnique();
  const attempted = Storage.countAttemptedUnique();
  if (top && top.count >= 2)
    return `Picking up where you left off: **${top.category}** has tripped you up ${top.count} times. Want a quick drill aimed at exactly that?`;
  if (attempted >= 3)
    return `You've attempted ${attempted} challenges and solved ${solved}. Want to push into a harder one?`;
  return null;
}

/**
 * Rolling summarization: instead of hard-truncating a long thread, fold the
 * oldest ~30% of turns into one short pseudo-message. Purely local — no network.
 */
const KEEP_TURNS = 14;
function compactHistory(history: ChatMessage[]): ChatMessage[] {
  if (history.length <= KEEP_TURNS) return history;
  const cut = Math.max(1, Math.floor(history.length * 0.3));
  const old = history.slice(0, cut);
  const rest = history.slice(cut);
  const asked = old.filter((m) => m.role === "user").map((m) => stripThink(m.content).slice(0, 90));
  const summary: ChatMessage = {
    role: "user",
    content: `[earlier in this session, summarized] The student asked about: ${asked.join(" | ") || "general concepts"}. Continue without repeating those explanations verbatim.`,
  };
  return [summary, ...rest];
}

interface Sketch {
  title: string;
  states: string[];
  edges: { from: number; to: number; label: string }[];
}

/** Generic illustrative sketch — dummy names only, never the student's machine. */
function parseSketch(spec: string, title: string): Sketch | null {
  const edges: Sketch["edges"] = [];
  const names: string[] = [];
  const idx = (n: string) => {
    const at = names.indexOf(n);
    if (at >= 0) return at;
    names.push(n);
    return names.length - 1;
  };
  for (const part of spec.split(";")) {
    const m = part.trim().match(/^([\w']+)\s*-\s*([^->]*)\s*->\s*([\w']+)$/);
    if (!m) continue;
    edges.push({ from: idx(m[1]!), to: idx(m[3]!), label: (m[2] || "").trim() || "·" });
  }
  if (!edges.length) return null;
  return { title, states: names, edges };
}

function ScratchDiagram({ sketch, onClear }: { sketch: Sketch; onClear: () => void }) {
  const positions = sketch.states.map((_, i) => ({ x: 46 + i * 88, y: 52 }));
  return (
    <div className="lab-card" style={{ margin: "0 10px 8px" }}>
      <div className="flex items-center gap-2">
        <p className="section-label" style={{ margin: 0 }}>
          Scratch sketch — generic example
        </p>
        <button className="tool-btn ml-auto" title="Clear sketch" onClick={onClear}>
          <X size={13} />
        </button>
      </div>
      <p className="text-[11px]" style={{ color: "var(--ink-muted)" }}>
        {sketch.title}
      </p>
      <svg
        role="img"
        aria-label={`Illustrative diagram: ${sketch.title}`}
        width="100%"
        height={104}
        viewBox={`0 0 ${Math.max(220, 46 + sketch.states.length * 88)} 104`}
      >
        {sketch.edges.map((e, i) => {
          const a = positions[e.from]!;
          const b = positions[e.to]!;
          if (e.from === e.to)
            return (
              <g key={i}>
                <path
                  d={`M ${a.x - 10} ${a.y - 18} q 10 -22 20 0`}
                  fill="none"
                  stroke="currentColor"
                  strokeWidth={1.2}
                  opacity={0.55}
                />
                <text
                  x={a.x}
                  y={a.y - 30}
                  textAnchor="middle"
                  fontSize={10}
                  fill="currentColor"
                  opacity={0.8}
                >
                  {e.label}
                </text>
              </g>
            );
          return (
            <g key={i}>
              <line
                x1={a.x + 18}
                y1={a.y}
                x2={b.x - 18}
                y2={b.y}
                stroke="currentColor"
                strokeWidth={1.2}
                opacity={0.55}
              />
              <text
                x={(a.x + b.x) / 2}
                y={a.y - 8}
                textAnchor="middle"
                fontSize={10}
                fill="currentColor"
                opacity={0.8}
              >
                {e.label}
              </text>
            </g>
          );
        })}
        {sketch.states.map((s, i) => (
          <g key={s}>
            <circle
              cx={positions[i]!.x}
              cy={positions[i]!.y}
              r={17}
              fill="none"
              stroke="currentColor"
              strokeWidth={1.3}
              opacity={0.8}
            />
            <text
              x={positions[i]!.x}
              y={positions[i]!.y + 4}
              textAnchor="middle"
              fontSize={11}
              fill="currentColor"
            >
              {s}
            </text>
          </g>
        ))}
      </svg>
    </div>
  );
}

export function TutorPanel({
  open,
  onClose,
  moduleId,
  getContext,
}: {
  open: boolean;
  onClose: () => void;
  moduleId: string;
  getContext: () => string;
}) {
  const [settings, setSettings] = useState<TutorSettings>(() => loadSettings());
  const [showSettings, setShowSettings] = useState(false);
  const [showKey, setShowKey] = useState(false);
  /** Live model catalog, fetched from whichever provider the student picked. */
  const [catalog, setCatalog] = useState<ModelInfo[]>([]);
  const [catalogError, setCatalogError] = useState<string | null>(null);
  const [loadingModels, setLoadingModels] = useState(false);
  const [freeOnly, setFreeOnly] = useState(false);
  const [modelFilter, setModelFilter] = useState("");
  const [messages, setMessages] = useState<ChatMessage[]>([
    { role: "assistant", content: GREETING },
  ]);
  const [input, setInput] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [chips, setChips] = useState<{ tab: string; label: string }[]>([]);
  const [sketch, setSketch] = useState<Sketch | null>(null);
  const [recs, setRecs] = useState<Recommendation[]>([]);
  const [narration, setNarration] = useState<string | null>(null);
  const scroller = useRef<HTMLDivElement | null>(null);
  const composer = useRef<HTMLInputElement | null>(null);
  /** Converter reveal tracking — feeds the sequencing guard. */
  const reveal = useRef<Record<string, boolean>>({});

  useEffect(() => {
    setSettings(loadSettings());
    const opener = recallOpener();
    if (opener) {
      setMessages((m) => (m.length === 1 ? [...m, { role: "assistant", content: opener }] : m));
      setRecs(buildRecommendations(2));
    }
  }, []);

  /** Speak (and show) a description of what is currently drawn on the canvas. */
  const describeCanvas = useRef(() => {});
  describeCanvas.current = () => {
    const text = narrateContext(getContext());
    setNarration(text);
    speak(text);
  };

  useEffect(() => {
    const onReveal = (e: Event) => {
      const d = (e as CustomEvent).detail as { moduleId: string; finalVisible: boolean };
      if (d?.moduleId) reveal.current[d.moduleId] = d.finalVisible;
    };
    window.addEventListener("iale-reveal-state", onReveal);
    return () => window.removeEventListener("iale-reveal-state", onReveal);
  }, []);

  useEffect(() => {
    if (open) composer.current?.focus();
  }, [open, moduleId]);

  useEffect(() => {
    if (!settings.apiKey && open) setShowSettings(true);
  }, [settings.apiKey, open]);

  useEffect(() => {
    scroller.current?.scrollTo({ top: scroller.current.scrollHeight, behavior: "smooth" });
  }, [messages, busy]);

  const rendered = useMemo(
    () => messages.map((m) => ({ role: m.role, ...splitThink(m.content) })),
    [messages],
  );

  function patch(next: Partial<TutorSettings>) {
    const merged = { ...settings, ...next };
    if (next.provider && next.provider !== settings.provider)
      merged.model = PROVIDERS[next.provider].models[0] ?? merged.model;
    setSettings(merged);
    saveSettings(merged);
  }

  /** Ask the provider itself what it can run — no hardcoded menu. */
  const alive = useRef(true);
  useEffect(() => {
    alive.current = true;
    return () => {
      alive.current = false;
    };
  }, []);
  const refreshModels = useRef(async () => {});
  useEffect(() => {
    refreshModels.current = async () => {
      setLoadingModels(true);
      setCatalogError(null);
      const res = await listModels(settings.provider, settings.apiKey);
      if (!alive.current) return;
      setLoadingModels(false);
      if (!res.ok) {
        setCatalog([]);
        setCatalogError(res.error);
        return;
      }
      setCatalog(res.models);
      if (!res.models.some((m) => m.id === settings.model) && res.models[0])
        patch({ model: res.models[0].id });
    };
  });

  // Auto-load the catalog when the panel is open and the provider/key settles.
  useEffect(() => {
    if (!open || !showSettings) return;
    const p = PROVIDERS[settings.provider];
    if (p.listNeedsKey && settings.apiKey.trim().length < 8) return;
    const t = window.setTimeout(() => void refreshModels.current(), 600);
    return () => window.clearTimeout(t);
  }, [open, showSettings, settings.provider, settings.apiKey]);

  const visibleModels = useMemo(() => {
    const q = modelFilter.trim().toLowerCase();
    return catalog.filter(
      (m) =>
        (!freeOnly || m.free === true) &&
        (!q || m.id.toLowerCase().includes(q) || m.label.toLowerCase().includes(q)),
    );
  }, [catalog, freeOnly, modelFilter]);

  async function send() {
    const question = input.trim();
    if (!question || busy) return;
    const history = compactHistory([
      ...messages
        .filter((m) => m.content !== GREETING)
        .map((m) => ({ ...m, content: stripThink(m.content) })),
      { role: "user" as const, content: question },
    ]);
    setMessages((m) => [...m, { role: "user", content: question }]);
    setInput("");
    setBusy(true);
    setError(null);

    const res = await askTutor(settings, getContext().slice(0, 6000), history.slice(-24));
    setBusy(false);

    if (!res.ok) {
      setError(res.error);
      return;
    }
    const { cleanText, actions } = parseTutorActions(res.text);
    const verdict = checkReply(stripThink(cleanText), {
      moduleId,
      finalVisible: reveal.current[moduleId] ?? true,
    });
    const finalText = verdict.allowed ? cleanText : verdict.fallback;
    setMessages((m) => [...m, { role: "assistant", content: finalText }]);
    composer.current?.focus();
    if (!verdict.allowed) return;

    dispatchTutorActions(actions);
    for (const a of actions) {
      if (a.type === "linkConcept")
        setChips((c) =>
          [...c.filter((x) => x.tab !== a.tab), { tab: a.tab, label: a.label }].slice(-3),
        );
      if (a.type === "readAloud") speak(a.text);
      if (a.type === "describeCanvas") describeCanvas.current();
      if (a.type === "showRecommendations") setRecs(buildRecommendations(3));
      if (a.type === "sketch") setSketch(parseSketch(a.spec, a.title));
      if (a.type === "exportNotes")
        exportNotes([...messages, { role: "assistant", content: finalText }]);
    }
  }

  /**
   * Study sheet export.
   *
   * Every assistant line is re-checked against the SAME reveal boundary that
   * was live during the session, so a note sheet from an unsolved exercise can
   * never hand the student, after the fact, something the tutor declined to say
   * out loud at the time.
   */
  function exportNotes(thread: ChatMessage[]) {
    const ctx = { moduleId, finalVisible: reveal.current[moduleId] ?? true };
    let redacted = 0;
    const body = thread
      .map((m) => {
        const text = stripThink(m.content);
        if (m.role !== "assistant") return `You: ${text}`;
        const verdict = checkReply(text, ctx);
        if (verdict.allowed) return `Socratic: ${text}`;
        redacted++;
        return "Socratic: [withheld — this exercise is still open, so the note sheet keeps the same boundary the session did]";
      })
      .join("\n\n");
    const footer = redacted
      ? `\n\n(${redacted} passage${redacted === 1 ? "" : "s"} withheld while this exercise is unsolved.)\n`
      : "\n";
    const url = URL.createObjectURL(
      new Blob([`IALE session notes — ${moduleId}\n\n${body}\n${footer}`], { type: "text/plain" }),
    );
    const a = document.createElement("a");
    a.href = url;
    a.download = `iale-session-${moduleId}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  }

  if (!open) return null;
  const provider = PROVIDERS[settings.provider];

  return (
    <aside className="tutor-panel">
      <header className="tutor-head">
        <Bot size={16} style={{ color: "var(--signal-blue)" }} />
        <span className="font-semibold text-sm">Socratic</span>
        <span className="badge" data-tone={settings.apiKey ? "accept" : "amber"}>
          {settings.apiKey ? provider.label.split(" ")[0] : "no key"}
        </span>
        <div className="ml-auto flex items-center gap-1">
          <button
            className="tool-btn"
            title="Read the last reply aloud"
            aria-label="Read the last reply aloud"
            onClick={() => speak(stripThink(messages[messages.length - 1]?.content ?? ""))}
          >
            <Volume2 size={15} />
          </button>
          <button
            className="tool-btn"
            title="Describe the canvas aloud"
            aria-label="Describe the canvas aloud"
            onClick={() => describeCanvas.current()}
          >
            <Ear size={15} />
          </button>
          <button
            className="tool-btn"
            title="Download session notes"
            onClick={() => exportNotes(messages)}
          >
            <Download size={15} />
          </button>
          <button
            className="tool-btn"
            title="Tutor settings"
            onClick={() => setShowSettings((s) => !s)}
          >
            <Settings2 size={15} />
          </button>
          <button className="tool-btn" title="Close tutor" onClick={onClose}>
            <X size={15} />
          </button>
        </div>
      </header>

      {showSettings && (
        <div className="tutor-settings">
          <p className="section-label">Bring your own key</p>
          <p className="text-[11.5px] leading-relaxed" style={{ color: "var(--ink-muted)" }}>
            Your key is stored only in this browser and is sent directly to the provider. Nothing is
            proxied through this app, and no one else pays for your usage.
          </p>
          <label className="section-label">Provider</label>
          <select
            className="field-input"
            value={settings.provider}
            onChange={(e) => patch({ provider: e.target.value as ProviderId })}
          >
            {PROVIDER_LIST.map((p) => (
              <option key={p.id} value={p.id}>
                {p.label}
              </option>
            ))}
          </select>
          <div className="flex items-center gap-2">
            <label className="section-label" style={{ margin: 0 }}>
              Model
            </label>
            <label
              className="ml-auto flex items-center gap-1 text-[11px]"
              style={{ color: "var(--ink-muted)" }}
            >
              <input
                type="checkbox"
                checked={freeOnly}
                onChange={(e) => setFreeOnly(e.target.checked)}
              />
              Free only
            </label>
            <button
              className="tool-btn"
              title="Refresh model list from the provider"
              aria-label="Refresh model list"
              onClick={() => void refreshModels.current()}
            >
              <RefreshCw size={13} className={loadingModels ? "animate-spin" : undefined} />
            </button>
          </div>
          <input
            className="field-input"
            placeholder="Filter models…"
            value={modelFilter}
            onChange={(e) => setModelFilter(e.target.value)}
          />
          <select
            className="field-input"
            value={settings.model}
            onChange={(e) => patch({ model: e.target.value })}
          >
            {!visibleModels.some((m) => m.id === settings.model) && settings.model && (
              <option value={settings.model}>{settings.model} (current)</option>
            )}
            {visibleModels.map((m) => (
              <option key={m.id} value={m.id}>
                {m.label === m.id ? m.id : `${m.label} — ${m.id}`}
                {m.free ? "  · free" : ""}
              </option>
            ))}
          </select>
          <p className="text-[11px]" style={{ color: "var(--ink-muted)" }}>
            {loadingModels
              ? "Fetching the live model catalog…"
              : catalogError
                ? catalogError
                : catalog.length
                  ? `${visibleModels.length} of ${catalog.length} chat-capable models${
                      freeOnly ? " (free ones only)" : ""
                    }.`
                  : "Paste your key to load this provider's live model list."}
            {freeOnly && catalog.length > 0 && !catalog.some((m) => m.free) && (
              <> This provider publishes no pricing, so nothing can be proven free.</>
            )}
          </p>

          <label className="section-label">API key</label>
          <div className="flex gap-1">
            <input
              className="field-input"
              type={showKey ? "text" : "password"}
              autoComplete="off"
              spellCheck={false}
              placeholder={provider.keyPlaceholder}
              value={settings.apiKey}
              onChange={(e) => patch({ apiKey: e.target.value })}
            />
            <button
              className="tool-btn"
              title={showKey ? "Hide key" : "Show key"}
              onClick={() => setShowKey((s) => !s)}
            >
              {showKey ? <EyeOff size={15} /> : <Eye size={15} />}
            </button>
          </div>
          <a
            className="inline-flex items-center gap-1 text-[11.5px]"
            style={{ color: "var(--signal-blue)" }}
            href={provider.keysUrl}
            target="_blank"
            rel="noreferrer"
          >
            <KeyRound size={12} /> Get a {provider.label} key <ExternalLink size={11} />
          </a>
        </div>
      )}

      <div className="tutor-thread" ref={scroller}>
        {rendered.map((m, i) => (
          <div key={i} className="tutor-msg" data-role={m.role}>
            {m.think && (
              <details style={{ marginBottom: 6 }}>
                <summary
                  className="text-[11px] cursor-pointer"
                  style={{ color: "var(--ink-muted)" }}
                >
                  How I reasoned
                </summary>
                <div className="text-[11px] leading-relaxed" style={{ color: "var(--ink-muted)" }}>
                  {m.think}
                </div>
              </details>
            )}
            <div className="tutor-prose">
              <ReactMarkdown>{m.body}</ReactMarkdown>
            </div>
          </div>
        ))}
        {busy && (
          <div className="tutor-msg" data-role="assistant" style={{ color: "var(--ink-muted)" }}>
            Thinking…
          </div>
        )}
        {error && (
          <div className="tutor-msg" data-role="error">
            {error}
          </div>
        )}
      </div>

      {narration && (
        <div className="lab-card" style={{ margin: "0 10px 8px" }} aria-live="polite">
          <div className="flex items-center gap-2">
            <p className="section-label" style={{ margin: 0 }}>
              Canvas description
            </p>
            <button
              className="tool-btn ml-auto"
              title="Dismiss description"
              aria-label="Dismiss canvas description"
              onClick={() => setNarration(null)}
            >
              <X size={13} />
            </button>
          </div>
          <p className="text-[11.5px] leading-relaxed" style={{ color: "var(--ink-muted)" }}>
            {narration}
          </p>
        </div>
      )}

      {recs.length > 0 && (
        <div className="lab-card" style={{ margin: "0 10px 8px" }}>
          <div className="flex items-center gap-2">
            <p className="section-label" style={{ margin: 0 }}>
              Recommended drills
            </p>
            <button
              className="tool-btn ml-auto"
              title="Dismiss recommendations"
              aria-label="Dismiss recommendations"
              onClick={() => setRecs([])}
            >
              <X size={13} />
            </button>
          </div>
          <div className="flex flex-col gap-1.5">
            {recs.map((r) => (
              <button
                key={r.challenge.id}
                className="btn-ghost text-left"
                style={{ display: "block", width: "100%" }}
                onClick={() => {
                  window.dispatchEvent(
                    new CustomEvent("iale-load-challenge", {
                      detail: { id: r.challenge.id, category: r.category },
                    }),
                  );
                  window.dispatchEvent(
                    new CustomEvent("iale-tutor-action", {
                      detail: { type: "gotoTab", tab: "debugger" },
                    }),
                  );
                  setRecs([]);
                }}
              >
                <span className="text-[12px] font-semibold">{r.challenge.name}</span>
                <span
                  className="block text-[11px] leading-snug"
                  style={{ color: "var(--ink-muted)" }}
                >
                  {r.reason}
                </span>
              </button>
            ))}
          </div>
        </div>
      )}

      {sketch && <ScratchDiagram sketch={sketch} onClear={() => setSketch(null)} />}

      {chips.length > 0 && (
        <div className="flex flex-wrap gap-1" style={{ padding: "0 10px 8px" }}>
          {chips.map((c) => (
            <button
              key={c.tab}
              className="chip"
              onClick={() => {
                window.dispatchEvent(
                  new CustomEvent("iale-tutor-action", { detail: { type: "gotoTab", tab: c.tab } }),
                );
                setChips((x) => x.filter((y) => y.tab !== c.tab));
              }}
            >
              {c.label}
            </button>
          ))}
        </div>
      )}

      <div className="tutor-compose">
        <input
          ref={composer}
          className="field-input"
          placeholder={settings.apiKey ? "Ask about your machine…" : "Add your API key to start"}
          value={input}
          onChange={(e) => setInput(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === "Enter" && !e.shiftKey) {
              e.preventDefault();
              void send();
            }
          }}
        />
        <button
          className="btn-primary"
          onClick={() => void send()}
          disabled={busy || !input.trim()}
          title="Send"
        >
          <Send size={14} />
        </button>
      </div>
    </aside>
  );
}
